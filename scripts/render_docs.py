"""Generate the per-scenario READMEs and the generated blocks in other docs from the code.

Output blocks are the real output of the code, code excerpts are cut from the source with ``inspect``.
``--check`` fails if any generated file differs from what is committed (the doc-drift check in CI).
"""

from __future__ import annotations

import argparse
import inspect
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
os.environ["LANGSMITH_TRACING"] = "false"
os.environ.pop("LANGSMITH_API_KEY", None)

from scenario_notes import N  # noqa: E402

from lcstack.scenarios import MODULES, load  # noqa: E402

CREDIT = "Section titles follow the *LangChain & LangGraph Cheat Sheet* by AI Engineering Insider; all text and code here are original."


def run_quiet(fn):
    return fn()


def excerpt(mod, name: str) -> str:
    """Top-level ``def``/``class`` named ``name`` with its decorators, cut from the module source."""
    lines = Path(mod.__file__).read_text().splitlines()
    pat = re.compile(rf"^(async def|def|class) {re.escape(name)}\b")
    i = next(k for k, line in enumerate(lines) if pat.match(line))
    while i > 0 and lines[i - 1].startswith("@"):
        i -= 1
    j = i + 1
    while j < len(lines) and not lines[j].startswith("@") and not re.match(r"^(async def|def|class) ", lines[j]):
        if lines[j] and not lines[j][0].isspace() and not lines[j].startswith((")", "]")):
            break
        j += 1
    while lines[j - 1].strip() == "":
        j -= 1
    return "\n".join(lines[i:j])


def tests_for(number: int, module: str) -> list[str]:
    found = []
    for f in sorted((ROOT / "tests").glob("test_*.py")):
        src = f.read_text()
        if module in src or f.name.startswith(f"test_s{number:02d}_"):
            names = re.findall(r"^def (test_\w+)", src, re.M)
            found.append(f"`tests/{f.name}`: " + ", ".join(f"`{n}`" for n in names))
    found.append("`tests/test_scenarios.py`: `test_scenario_runs_and_is_deterministic`, `test_scenario_has_readme_and_module`")
    return found


def scenario_readme(n: int) -> str:
    mod = load(n)
    m, notes = mod.META, N[n]
    doc = inspect.cleandoc(mod.__doc__ or "")
    title, _, body = doc.partition("\n")
    out = run_quiet(mod.run)
    parts = [
        f"# {m.number:02d} {m.section}",
        "",
        "<!-- generated by scripts/render_docs.py; edit scripts/scenario_notes.py or the module docstring -->",
        "",
        f"**Concept:** {m.concept}  ",
        f"**Client (fictional):** {m.client} ({m.domain})  ",
        f"**Code:** [`{m.module}`](../../{m.module})  ",
        f"**Run:** `lcstack run {m.number:02d}`",
        "",
        "## Purpose",
        "",
        title.split(": ", 1)[-1],
        "",
        body.strip(),
        "",
        "## Flow",
        "",
        "```mermaid",
        notes["mermaid"],
        "```",
        "",
        "## How it works",
        "",
        *[f"- {h}" for h in notes["how"]],
        "",
        "## Code excerpts",
        "",
    ]
    for name in notes["excerpts"]:
        parts += [f"`{name}`:", "", "```python", excerpt(mod, name), "```", ""]
    parts += [
        "## Real output",
        "",
        f"Produced by `lcstack run {m.number:02d}` with the offline scripted model (no API keys). Regenerate with `python scripts/render_docs.py`.",
        "",
        "```text",
        *out,
        "```",
        "",
        "## Tests",
        "",
        *[f"- {t}" for t in tests_for(n, MODULES[n - 1])],
        "",
        "## Gotchas",
        "",
        *[f"- {g}" for g in notes["gotchas"]],
        "",
        "## Interview points",
        "",
        *[f"- {i}" for i in notes["interview"]],
        "",
        "---",
        "",
        CREDIT,
        "",
    ]
    return "\n".join(parts)


def readme_table() -> str:
    rows = ["| # | Section | Concept | Client use case (fictional) | Folder | Command | Tests |", "|---|---|---|---|---|---|---|"]
    for n in range(1, len(MODULES) + 1):
        m = load(n).META
        tfile = f"tests/test_s{n:02d}_{MODULES[n - 1][4:]}.py"
        tests = [t.split("`")[1] for t in tests_for(n, MODULES[n - 1])]
        trefs = ", ".join(f"[{Path(t).name}]({t})" for t in tests if Path(ROOT, t).exists()) or tfile
        rows.append(f"| {n:02d} | {m.section} | {m.concept} | {m.client} | [{m.folder}]({m.folder}/README.md) | `lcstack run {n:02d}` | {trefs} |")
    return "\n".join(rows)


def capstone_block(action: str) -> str:
    from lcstack.capstone.cli import action as run_action

    return "\n".join(run_quiet(lambda: run_action(action)))


def eval_block() -> str:
    from lcstack.capstone.evals import report

    return "\n".join(run_quiet(lambda: report(compare=True)))


def gate_block() -> str:
    from lcstack.capstone.gate import run_gate

    return "\n".join(run_quiet(lambda: run_gate()[0]))


GENERATORS = {
    "scenario-table": readme_table,
    "capstone-demo": lambda: "```text\n" + capstone_block("demo") + "\n```",
    "capstone-trace": lambda: "```text\n" + capstone_block("trace") + "\n```",
    "capstone-stream": lambda: "```text\n" + capstone_block("stream") + "\n```",
    "capstone-hitl": lambda: "```text\n" + capstone_block("hitl") + "\n```",
    "capstone-monitor": lambda: "```text\n" + capstone_block("monitor") + "\n```",
    "capstone-feedback": lambda: "```text\n" + capstone_block("feedback") + "\n```",
    "capstone-prompts": lambda: "```text\n" + capstone_block("prompts") + "\n```",
    "capstone-architecture": lambda: (
        "```mermaid\nflowchart TD\n" + "\n".join("  " + x for x in capstone_block("architecture").splitlines()) + "\n```"
    ),
    "eval-compare": lambda: "```text\n" + eval_block() + "\n```",
    "gate": lambda: "```text\n" + gate_block() + "\n```",
}
BLOCK = re.compile(r"(<!-- BEGIN (?P<name>[\w-]+) -->\n)(.*?)(<!-- END (?P=name) -->)", re.S)


def fill_blocks(text: str, cache: dict) -> str:
    def sub(mt):
        name = mt.group("name")
        if name not in cache:
            cache[name] = GENERATORS[name]()
        return mt.group(1) + cache[name] + "\n" + mt.group(4)

    return BLOCK.sub(sub, text)


def targets() -> dict[Path, str]:
    files, cache = {}, {}
    for n in range(1, len(MODULES) + 1):
        files[ROOT / load(n).META.folder / "README.md"] = scenario_readme(n)
    for p in [ROOT / "README.md", *sorted((ROOT / "docs").rglob("*.md"))]:
        if p.exists() and "<!-- BEGIN " in p.read_text():
            files[p] = fill_blocks(p.read_text(), cache)
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    stale = []
    for path, text in targets().items():
        if path.exists() and path.read_text() == text:
            continue
        if a.check:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("docs out of date, run python scripts/render_docs.py:", *stale, sep="\n  ")
        return 1
    print("docs up to date" if a.check else "done")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
